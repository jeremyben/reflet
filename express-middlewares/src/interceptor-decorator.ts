import { Use } from '@reflet/express'
import * as express from 'express'
import { ResponseSafe } from './interfaces'
import { isPromise } from './type-guards'
import { nextOnRejection } from './next-on-rejection'

/**
 * Intercepts and manipulates the response body.
 * @param transform - mapper function that takes the intercepted response body and must return the modified response body. _Gives access to Request and Response objects._
 *
 * @remarks
 * **Errors:**
 * It won't intercept errors, whether the body is an `Error` instance or the status is >= 400.
 * Instead you should use a `@Catch` decorator.
 * If the transform throws or rejects, the error is passed to the error handlers.
 *
 * **Order:**
 * Successive interceptors transform the body in the reverse order they are written (the closest to the method first).
 *
 * **Redirections:**
 * It won't intercept redirections either (status 3xx, e.g. `res.redirect`), whose body is generated by express.
 *
 * **Streams:**
 * It won't intercept streaming responses either (_e.g. files sent with `res.sendFile`_).
 * Instead you should use a [transform stream](https://nodejs.org/api/stream.html#stream_class_stream_transform).
 * In fact, it won't intercept any data sent with `res.write` native method.
 *
 * Works by patching `res.send`, `res.json`, `res.jsonp` and `res.end` methods.
 *
 * @example
 * ```ts
 * ＠UseInterceptor<{ foo: number }>((data, context) => {
 *   return { foo: data.foo * 5 }
 * })
 * ＠Get('/')
 * get(＠Res res: Response) {
 *   res.send({ foo: 1 }) // expect { foo: 5 }
 * }
 * ```
 * ------
 * @public
 */
export function UseInterceptor<In, Out = In>(
	transform: (
		data: In,
		context: { req: express.Request; res: ResponseSafe }
	) => Out extends void ? never : Out | Promise<Out>
) {
	return Use((req, res: express.Response, next) => {
		const send0 = res.send
		const json0 = res.json
		const jsonp0 = res.jsonp
		const end0 = res.end

		// Express gives route middlewares the `next` of the route, and router middlewares the `next` of the router (also exposed as `req.next`).
		// Applied on a route, the interceptor forwards transform errors to its own `next`, to reach the route error handlers.
		// Otherwise, it forwards them to the `next` of the router sending the response, as it has already called its own `next`.
		const appliedOnRoute = next !== req.next

		function forwardError(error: unknown) {
			nextOnRejection(appliedOnRoute ? next : req.next || next)(error)
		}

		// object bodies go through: res.send -> res.json (to stringify itself) -> res.send -> res.end,
		// so to avoid transforming twice, we patch each method back to the orignal.
		// https://github.com/expressjs/express/blob/4.x/lib/response.js#L158
		// That's what express-mung does:
		// https://github.com/richardschneider/express-mung/blob/v0.5.1/index.js#L72
		function restore() {
			res.send = send0
			res.json = json0
			res.jsonp = jsonp0
			res.end = end0
		}

		function intercept(original: (body: any) => express.Response) {
			return function (body: In) {
				restore()

				// Don't intercept errors and redirections.
				if (body instanceof Error || res.statusCode >= 300) {
					return original.call(res, body)
				}

				let result: Out | Promise<Out>

				// Forward synchronous errors as well, as the response might be sent outside the handler (e.g. in a callback).
				try {
					result = transform(body, { req, res })
				} catch (error) {
					forwardError(error)
					return res
				}

				// Response has been sent from the interceptor (bad bad programmer).
				if (res.writableEnded) {
					return res
				}

				if (isPromise(result)) {
					// Also forward errors of the original method (e.g. a body that can't be serialized).
					// Resolved as a native promise, as a thenable might not return one.
					return Promise.resolve(result)
						.then((value) => original.call(res, value))
						.catch(forwardError) as any
				} else {
					return original.call(res, result)
				}
			}
		}

		res.send = intercept(send0)
		res.json = intercept(json0)
		res.jsonp = intercept(jsonp0)

		// https://nodejs.org/api/http.html#http_response_end_data_encoding_callback
		// Typed loosely since it might return a promise if the transform is async.
		res.end = function end(
			dataOrCallback?: string | Buffer | (() => void),
			encodingOrCallback?: string | (() => void),
			callback?: () => void
		) {
			restore()

			// Don't intercept errors, redirections, responses already partly written,
			// or data parameter not fitting the right type.
			if (
				(typeof dataOrCallback !== 'string' && !Buffer.isBuffer(dataOrCallback)) ||
				res.statusCode >= 300 ||
				res.headersSent
			) {
				return end0.apply(res, arguments as unknown as Parameters<express.Response['end']>)
			}

			// The response is sent by the error handlers instead, so the callback waits for it to finish.
			const forwardEndError = (error: unknown) => {
				const endCallback = typeof encodingOrCallback === 'function' ? encodingOrCallback : callback
				if (endCallback) res.once('finish', endCallback)
				forwardError(error)
			}

			// Directly modify the data parameter.
			// Forward synchronous errors as well, as the response might be sent outside the handler (e.g. in a callback).
			try {
				arguments[0] = transform(dataOrCallback as any, { req, res })
			} catch (error) {
				forwardEndError(error)
				return res
			}

			// Response has been sent from the interceptor (bad bad programmer).
			/* istanbul ignore if - covered in res.send */
			if (res.writableEnded) {
				return res
			}

			if (isPromise(arguments[0])) {
				return Promise.resolve(arguments[0])
					.then((value: any) => {
						arguments[0] = value
						return end0.apply(res, arguments as unknown as Parameters<express.Response['end']>)
					})
					.catch(forwardEndError)
			} else {
				return end0.apply(res, arguments as unknown as Parameters<express.Response['end']>)
			}
		} as express.Response['end']

		next()
	})
}
